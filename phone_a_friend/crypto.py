"""Cryptographic primitives for phone_a_friend.

Every algorithm here is FIPS-approved, and every one is carried out by the
OpenSSL that the ``cryptography`` package is bound to:

* Identity keys are ECDH keypairs on NIST P-256 (SP 800-56A).
* Symmetric encryption is AES-256-GCM (SP 800-38D) with a 96-bit random
  nonce, prepended to the ciphertext.
* "Sealed" messages (invites) use an ephemeral P-256 key against the
  recipient's static public key, so anything can be pushed to a user knowing
  only their public identity key.
* Direct-message conversations are encrypted with a key derived from the
  static-static P-256 Diffie-Hellman shared secret of the two participants,
  so without one of the two private keys (plus the peer's public key) the
  messages cannot be read.
* Group conversations use a random symmetric group key that is pushed to
  invitees inside a sealed invite; each group's message key is derived from
  it.
* Key derivation is HKDF-SHA256 (SP 800-56C).
* The per-user config file is encrypted with a key derived from the user's
  passphrase with PBKDF2-HMAC-SHA256 (SP 800-132); it protects the private
  identity key, contact keys, and group keys.

Whether that OpenSSL is a *validated* module running in FIPS mode is a
property of the host, not of this code: :func:`fips_enabled` reports it.
The primitives of phone_a_friend 0.x (X25519, ChaCha20-Poly1305 and scrypt)
are not here; :mod:`phone_a_friend.legacy` keeps them only to read and
migrate data that 0.x wrote.
"""

from __future__ import annotations

import base64
import os

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives.kdf.pbkdf2 import PBKDF2HMAC

#: The format version written into every encrypted record. Records written
#: by 0.x have no version field at all; that absence is how they are known.
FORMAT = 2

NONCE_LEN = 12
TAG_LEN = 16
KEY_LEN = 32
PUB_LEN = 65  # X9.62 uncompressed P-256 point: 0x04 || X || Y

# PBKDF2 parameters for the passphrase KDF (SP 800-132; 600,000 iterations
# is OWASP's floor for PBKDF2-HMAC-SHA256)
PBKDF2_ITERATIONS = 600_000
SALT_LEN = 16

#: Names recorded in each config wrapper, so a reader knows what it holds.
KDF_NAME = "pbkdf2-hmac-sha256"
AEAD_NAME = "aes-256-gcm"


class DecryptError(Exception):
    """Raised when a payload cannot be decrypted/authenticated."""


class LegacyUnavailable(Exception):
    """This OpenSSL (typically one in FIPS mode) refuses the 0.x algorithms
    that :mod:`phone_a_friend.legacy` needs to read 0.x data."""


def b64e(data: bytes) -> str:
    return base64.b64encode(data).decode("ascii")


def b64d(data: str) -> bytes:
    return base64.b64decode(data.encode("ascii"))


def random_bytes(n: int) -> bytes:
    """The one source of randomness for symmetric keys, nonces and salts.

    ``cryptography`` has no public call into OpenSSL's DRBG, so this is the
    kernel's ``getrandom``. On RHEL 9 and Rocky 9 booted with ``fips=1``
    that is the kernel crypto API's SP 800-90A DRBG, inside the kernel's own
    validated module. Private keys are generated by OpenSSL itself
    (:func:`generate_private_key`)."""
    return os.urandom(n)


def _backend():
    from cryptography.hazmat.backends.openssl import backend

    return backend


def fips_enabled() -> bool:
    """True when the OpenSSL that ``cryptography`` uses is in FIPS mode."""
    return bool(getattr(_backend(), "_fips_enabled", False))


def openssl_version() -> str:
    return _backend().openssl_version_text()


def fips_status() -> str:
    """One line for ``paf --version`` and the start-up warning."""
    mode = "on" if fips_enabled() else "off"
    return f"{openssl_version()}, FIPS mode {mode}"


# ---------------------------------------------------------------- key pairs

def generate_private_key() -> ec.EllipticCurvePrivateKey:
    return ec.generate_private_key(ec.SECP256R1())


def private_key_bytes(priv: ec.EllipticCurvePrivateKey) -> bytes:
    return priv.private_bytes(
        serialization.Encoding.DER,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    )


def private_key_from_bytes(raw: bytes) -> ec.EllipticCurvePrivateKey:
    priv = serialization.load_der_private_key(raw, password=None)
    if not isinstance(priv, ec.EllipticCurvePrivateKey) or not isinstance(
        priv.curve, ec.SECP256R1
    ):
        raise ValueError("not a P-256 private key")
    return priv


def public_key_bytes(priv: ec.EllipticCurvePrivateKey) -> bytes:
    return priv.public_key().public_bytes(
        serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint
    )


def load_public_key(raw: bytes) -> ec.EllipticCurvePublicKey:
    """Parse and validate a peer's public key (raises ValueError)."""
    if len(raw) != PUB_LEN:
        raise ValueError("not a P-256 public key")
    return ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), raw)


def is_public_key(raw: bytes) -> bool:
    """True for a valid P-256 public key in this module's encoding."""
    try:
        load_public_key(raw)
    except ValueError:
        return False
    return True


def _ecdh(priv: ec.EllipticCurvePrivateKey, peer_pub: bytes) -> bytes:
    return priv.exchange(ec.ECDH(), load_public_key(peer_pub))


# ---------------------------------------------------------------- symmetric

def new_symmetric_key() -> bytes:
    return random_bytes(KEY_LEN)


def sym_encrypt(key: bytes, plaintext: bytes, aad: bytes = b"") -> bytes:
    nonce = random_bytes(NONCE_LEN)
    return nonce + AESGCM(key).encrypt(nonce, plaintext, aad)


def sym_decrypt(key: bytes, blob: bytes, aad: bytes = b"") -> bytes:
    if len(blob) < NONCE_LEN + TAG_LEN:
        raise DecryptError("ciphertext too short")
    try:
        return AESGCM(key).decrypt(blob[:NONCE_LEN], blob[NONCE_LEN:], aad)
    except InvalidTag as exc:
        raise DecryptError("authentication failed") from exc


# --------------------------------------------------------------- KDF helpers

def derive_passphrase_key(passphrase: str, salt: bytes, iterations: int) -> bytes:
    kdf = PBKDF2HMAC(
        algorithm=hashes.SHA256(), length=KEY_LEN, salt=salt, iterations=iterations
    )
    return kdf.derive(passphrase.encode("utf-8"))


def hkdf(secret: bytes, info: bytes) -> bytes:
    return HKDF(
        algorithm=hashes.SHA256(), length=KEY_LEN, salt=None, info=info
    ).derive(secret)


# --------------------------------------------------------------- sealed box

def seal(recipient_pub: bytes, plaintext: bytes) -> bytes:
    """Encrypt to a public key using an ephemeral sender key."""
    eph = generate_private_key()
    eph_pub = public_key_bytes(eph)
    shared = _ecdh(eph, recipient_pub)
    key = hkdf(shared, b"paf-seal-v2|" + eph_pub + recipient_pub)
    return eph_pub + sym_encrypt(key, plaintext)


def unseal(priv: ec.EllipticCurvePrivateKey, blob: bytes) -> bytes:
    if len(blob) < PUB_LEN + NONCE_LEN + TAG_LEN:
        raise DecryptError("sealed blob too short")
    eph_pub = blob[:PUB_LEN]
    my_pub = public_key_bytes(priv)
    try:
        shared = _ecdh(priv, eph_pub)
    except ValueError as exc:
        raise DecryptError("bad ephemeral key") from exc
    key = hkdf(shared, b"paf-seal-v2|" + eph_pub + my_pub)
    return sym_decrypt(key, blob[PUB_LEN:])


# ------------------------------------------------------------- pair-wise DM

def pair_key(my_priv: ec.EllipticCurvePrivateKey, their_pub: bytes) -> bytes:
    """Conversation key both parties can derive from their own private key
    and the peer's public key. Identical on both sides."""
    shared = _ecdh(my_priv, their_pub)
    my_pub = public_key_bytes(my_priv)
    lo, hi = sorted([my_pub, their_pub])
    return hkdf(shared, b"paf-dm-v2|" + lo + hi)


def group_message_key(group_key: bytes, gid: str) -> bytes:
    """The AES-256-GCM key for one group's messages, derived from the group
    key, so the group key is never used directly as a cipher key."""
    return hkdf(group_key, b"paf-grp-v2|" + gid.encode())
